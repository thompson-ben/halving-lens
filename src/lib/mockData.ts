function spark(seed: number, base: number, vol: number, len = 28): number[] {
  // Simple seeded random walk for sparklines / charts.
  let s = seed;
  const rand = () => {
    s = (s * 9301 + 49297) % 233280;
    return s / 233280;
  };
  const out: number[] = [];
  let v = base;
  for (let i = 0; i < len; i++) {
    v = v * (1 + (rand() - 0.48) * vol);
    out.push(v);
  }
  return out;
}

